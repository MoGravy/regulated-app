import Foundation

func check(_ value: Bool, _ message: String) { precondition(value, message) }
var e = ListeningEvidence(priorCreditSeconds: 0)
e.sample(position: 0, atMs: 0, eligible: true, discontinuity: false, duration: 100, wallAtMs: 1000000)
e.sample(position: 5, atMs: 5000, eligible: true, discontinuity: false, duration: 100, wallAtMs: 1005000)
check(e.seconds == 5, "actual playback earns credit")
e.sample(position: 5, atMs: 5000, eligible: false, discontinuity: false, duration: 100, wallAtMs: 1005000)
e.sample(position: 5, atMs: 15000, eligible: false, discontinuity: false, duration: 100, wallAtMs: 1015000)
e.sample(position: 10, atMs: 20000, eligible: false, discontinuity: false, duration: 100, wallAtMs: 1020000)
check(e.seconds == 5, "pause/buffer/mute/error intervals cannot earn credit")
e.sample(position: 10, atMs: 20000, eligible: true, discontinuity: false, duration: 100, wallAtMs: 1020000)
e.sample(position: 11, atMs: 21000, eligible: true, discontinuity: false, duration: 100, wallAtMs: 1021000)
e.sample(position: 90, atMs: 22000, eligible: true, discontinuity: true, duration: 100, wallAtMs: 1022000)
e.sample(position: 90, atMs: 23000, eligible: true, discontinuity: false, duration: 100, wallAtMs: 1023000)
e.sample(position: 91, atMs: 24000, eligible: true, discontinuity: false, duration: 100, wallAtMs: 1024000)
check(e.seconds == 7, "seek jump is fenced")
e.sample(position: 0, atMs: 24000, eligible: true, discontinuity: true, duration: 100, wallAtMs: 1024000)
e.sample(position: 0, atMs: 25000, eligible: true, discontinuity: false, duration: 100, wallAtMs: 1025000)
e.sample(position: 80, atMs: 105000, eligible: true, discontinuity: false, duration: 100, wallAtMs: 1105000)
check(e.seconds == 87 && e.qualifiedAtMs == 1098000, "background threshold time retained")
check(e.offsetMinutes == TimeZone.current.secondsFromGMT(for: Date(timeIntervalSince1970: e.qualifiedAtMs! / 1000)) / 60, "offset retains existing minutes east schema")
let qualified = e.qualifiedAtMs
e.sample(position: 80, atMs: 105000, eligible: true, discontinuity: false, duration: 100, wallAtMs: 1105000)
e.sample(position: 90, atMs: 104000, eligible: true, discontinuity: false, duration: 100, wallAtMs: 1105000)
check(e.seconds == 87 && e.qualifiedAtMs == qualified, "duplicate and backwards clock excluded")
e.sample(position: 91, atMs: 106000, eligible: true, discontinuity: false, duration: 100, wallAtMs: 1106000)
check(e.seconds == 87, "backwards clock fences the next interval too")
var retry = ListeningEvidence(priorCreditSeconds: 50)
retry.sample(position: 0, atMs: 0, eligible: true, discontinuity: false, duration: 100, wallAtMs: 2000000)
retry.sample(position: 30, atMs: 30000, eligible: true, discontinuity: false, duration: 100, wallAtMs: 2030000)
check(retry.seconds == 30 && retry.qualifiedAtMs == 2030000, "retry seeds only qualification")
var shortTrack = ListeningEvidence(priorCreditSeconds: 0)
shortTrack.sample(position: 0, atMs: 0, eligible: true, discontinuity: false, duration: 30, wallAtMs: 2000000)
shortTrack.sample(position: 90, atMs: 90000, eligible: true, discontinuity: false, duration: 30, wallAtMs: 2090000)
check(shortTrack.qualifiedAtMs == nil, "short tracks never qualify")
