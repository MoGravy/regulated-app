import assert from 'node:assert/strict'
import { chromium } from '@playwright/test'
import { mkdir } from 'node:fs/promises'
const target = process.env.ABOUT_CHECK_URL || 'http://127.0.0.1:4173'
await mkdir('.tmp/about-release-evidence', { recursive: true })
const browser = await chromium.launch({ headless: true })
try {
  for (const look of ['admiralty', 'night']) for (const width of [320, 390]) {
    const context = await browser.newContext({ viewport: { width, height: 844 }, serviceWorkers: 'block' })
    await context.addInitScript(() => localStorage.setItem('regulated_onboarding', 'true'))
    await context.route('**/*', async route => {
      const url = new URL(route.request().url())
      if (url.pathname.startsWith('/api/')) return route.fulfill({ json: url.pathname === '/api/check-subscription' ? { active: false } : {}, status: 200 })
      if (url.origin === new URL(target).origin) return route.continue()
      if (url.hostname.endsWith('supabase.co') || url.hostname.endsWith('supabase.invalid')) return route.fulfill({ json: [], status: 200 })
      if (url.hostname === 'js.stripe.com') return route.fulfill({ body: 'window.Stripe = () => ({})', contentType: 'application/javascript' })
      return route.abort()
    })
    const page = await context.newPage()
    const errors = []
    page.on('pageerror', error => errors.push(error.message))
    await page.goto(`${target}/premium?look=${look}`)
    await page.getByRole('link', { name: 'About Matthew', exact: true }).waitFor()
    const entry = page.getByRole('link', { name: 'About Matthew', exact: true })
    const bounds = await entry.boundingBox()
    assert.ok(bounds.width >= width - 50 && bounds.height >= 85)
    assert.ok(bounds.x >= 0 && bounds.x + bounds.width <= width && bounds.y >= 0 && bounds.y + bounds.height <= 844)
    assert.equal(await entry.locator('span span').first().evaluate(el => getComputedStyle(el).fontSize), '22px')
    assert.ok((await entry.innerText()).includes('One-to-one programmes'))
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true)
    await entry.focus()
    assert.equal(await entry.evaluate(el => document.activeElement === el), true)
    assert.notEqual(await entry.evaluate(el => getComputedStyle(el).boxShadow), 'none')
    assert.equal(await entry.evaluate(el => el.style.background), 'var(--control)')
    assert.equal(await entry.evaluate(el => el.style.color), 'var(--on-control)')
    const ratios = await entry.evaluate(el => {
      const rgb = value => value.match(/[\d.]+/g).slice(0, 3).map(Number)
      const luminance = values => values.map(v => v / 255).map(v => v <= .04045 ? v / 12.92 : ((v + .055) / 1.055) ** 2.4).reduce((sum, v, i) => sum + v * [.2126, .7152, .0722][i], 0)
      const bg = luminance(rgb(getComputedStyle(el).backgroundColor))
      return [...el.querySelectorAll('span span')].map(label => {
        const fg = luminance(rgb(getComputedStyle(label).color))
        return (Math.max(fg, bg) + .05) / (Math.min(fg, bg) + .05)
      })
    })
    assert.ok(ratios.every(ratio => ratio >= 4.5), `Readable card contrast: ${ratios}`)
    await page.evaluate(async () => { await Promise.all(document.getAnimations().filter(a => Number.isFinite(a.effect.getTiming().iterations)).map(a => a.finished.catch(() => {}))) })
    await page.screenshot({ path: `.tmp/about-release-evidence/${new URL(target).hostname}-${look}-${width}-you.png` })
    await page.evaluate(() => window.aboutDocumentMarker = 'retained')
    await page.getByRole('link', { name: 'About Matthew', exact: true }).press('Enter')
    await page.getByRole('heading', { name: 'About Matthew', exact: true }).waitFor()
    assert.equal(new URL(page.url()).pathname, '/about')
    assert.equal(await page.evaluate(() => window.aboutDocumentMarker), 'retained')
    assert.equal(await page.locator('html').getAttribute('data-look'), look)
    const cta = page.getByRole('link', { name: 'Email Matthew about working together', exact: true })
    const mail = new URL(await cta.getAttribute('href'))
    assert.equal(mail.pathname, 'info@matthewtweediehypnosis.com.au')
    assert.equal(mail.searchParams.get('subject'), 'One-to-one programme enquiry from Regulated')
    assert.deepEqual([...mail.searchParams.keys()], ['subject'])
    assert.ok((await page.locator('main').innerText()).includes('am completing a Master of Counselling'))
    assert.equal(await page.getByRole('navigation', { name: 'Primary' }).getByRole('button').count(), 5)
    await cta.focus()
    assert.equal(await cta.evaluate(element => document.activeElement === element), true)
    await cta.scrollIntoViewIfNeeded()
    await page.evaluate(async () => { await Promise.all(document.getAnimations().filter(a => Number.isFinite(a.effect.getTiming().iterations)).map(a => a.finished.catch(() => {}))) })
    await page.screenshot({ path: `.tmp/about-release-evidence/${new URL(target).hostname}-${look}-${width}.png` })
    await page.getByRole('link', { name: 'Back', exact: true }).click()
    await page.getByRole('link', { name: 'About Matthew', exact: true }).waitFor()
    assert.equal(await page.evaluate(() => window.aboutDocumentMarker), 'retained')
    await page.getByRole('link', { name: 'About Matthew', exact: true }).click()
    await page.reload()
    await page.getByRole('heading', { name: 'About Matthew', exact: true }).waitFor()
    assert.equal(await page.locator('html').getAttribute('data-look'), look)
    assert.deepEqual(errors, [])
    console.log(`PASS: ${target} ${look} ${width}px actual app About entry, client routing, Back, reload, five tabs, copy and mailto; APIs intercepted, no provider writes`)
    await context.close()
  }
} finally { await browser.close() }
